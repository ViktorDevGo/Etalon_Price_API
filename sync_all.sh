#!/bin/bash
# Полная синхронизация всех данных 4tochki

set -e

echo "=================================================================="
echo "Полная синхронизация данных 4tochki"
echo "Время начала: $(date '+%Y-%m-%d %H:%M:%S')"
echo "=================================================================="
echo ""

# 1. Синхронизация складов
echo "1. Синхронизация складов..."
echo "------------------------------------------------------------------"
go run cmd/sync-warehouses/main.go
echo ""

# 2. Синхронизация номенклатуры
echo "2. Синхронизация номенклатуры (XML)..."
echo "------------------------------------------------------------------"
go run cmd/sync-nomenclature/main.go -type=all
echo ""

# 3. Синхронизация цен и остатков
echo "3. Синхронизация цен и остатков (API)..."
echo "------------------------------------------------------------------"
go run cmd/sync-prices/main.go -type=all
echo ""

echo "=================================================================="
echo "Полная синхронизация завершена: $(date '+%Y-%m-%d %H:%M:%S')"
echo "=================================================================="
echo ""

# Показать статистику
echo "Итоговая статистика:"
echo "------------------------------------------------------------------"
go run cmd/check-warehouses/main.go | grep "Всего складов"
go run cmd/check-nomenclature/main.go | grep "Таблица"
go run cmd/check-prices/main.go | grep -E "(Шины|Диски):"
echo ""
